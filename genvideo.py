# 解析文字信息函数
def parse_text_data(text_data, display_duration=5, fps=24):
    lines = text_data.strip().split("\n")
    texts = []
    for line in lines:
        parts = line.split("，时间: ")
        text = parts[0].strip()
        time_str = parts[1].strip()
        minutes, seconds = map(int, time_str.split(":"))
        start_time = (minutes * 60 + seconds) * fps
        end_time = start_time + display_duration * fps
        texts.append((text, start_time, end_time))
    return texts


# 将文字信息解析成列表
