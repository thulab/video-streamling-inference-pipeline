fps = cap.get(cv2.CAP_PROP_FPS)
width = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
height = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))

# 创建输出视频
fourcc = cv2.VideoWriter_fourcc(*"mp4v")
out = cv2.VideoWriter(output_path, fourcc, fps, (width, height))

# 字体设置
font_path = "C:\\Windows\\Fonts\\msyh.ttc"  # 微软雅黑字体路径
font_size = 24
font = ImageFont.truetype(font_path, font_size)

current_text_index = 0
current_text, start_frame, end_frame = texts[current_text_index]

frame_number = 0
while cap.isOpened():
    ret, frame = cap.read()
    if not ret:
        break

    # 检查当前帧是否需要更新文本
    if frame_number > end_frame and current_text_index < len(texts) - 1:
        current_text_index += 1
        current_text, start_frame, end_frame = texts[current_text_index]

    # frame = cv2.flip(frame, 0)
    if start_frame <= frame_number <= end_frame:
        # 使用Pillow处理文字
        img_pil = Image.fromarray(frame)
        draw = ImageDraw.Draw(img_pil)
        # 获取文本的边界框
        text_bbox = draw.textbbox((0, 0), current_text, font=font)
        text_width = text_bbox[2] - text_bbox[0]
        text_height = text_bbox[3] - text_bbox[1]
        draw.rectangle([0, 0, text_width, text_height], fill="black")
        draw.text((0, 0), current_text, font=font, fill="white")

        frame = np.array(img_pil)

    out.write(frame)
    frame_number += 1

cap.release()
out.release()
print("视频处理完成！")
